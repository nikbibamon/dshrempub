'use strict';
const MODEL_REV = 16;
const LEVELS = ['independent', 'after_hint', 'after_explanation', 'after_answer'];
const EXPOSURE = { hint: 1, explanation: 2, answer: 3 };
const TRUTH = ['correct', 'defective', 'ambiguous'];

const SCALE = Object.freeze({
  version: 'tvijo.learn.scale/1',
  check: 1, justified: 2, checkCapPerCandidate: 2,
  credited: new Set(['trusted_test_run', 'counterexample_run', 'review_reproduction']),
  streakWindow: 5, streakThreshold: 3, watchRun: 2,
});

const HEX64 = /^[0-9a-f]{64}$/, HEX32 = /^[0-9a-f]{32}$/;
const ID = /^[a-z0-9][a-z0-9-]{0,63}$/, EXERCISE = /^[a-z0-9-]{1,40}\/[0-9]{1,3}$/, FLAG = /^[a-z0-9_]{1,40}$/, CHECK_ID = /^chk-[0-9]{1,4}$/;
const TS = /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d{1,3})?Z$/, VERSION = /^\d{1,3}\.\d{1,3}\.\d{1,3}$/;
const T = {
  hex64: (v) => typeof v === 'string' && HEX64.test(v), hex32: (v) => typeof v === 'string' && HEX32.test(v),
  id: (v) => typeof v === 'string' && ID.test(v), checkId: (v) => typeof v === 'string' && CHECK_ID.test(v), bool: (v) => typeof v === 'boolean',
  int: (v) => Number.isSafeInteger(v) && v >= 0 && v <= 2 ** 31, intOrNull: (v) => v === null || (Number.isSafeInteger(v) && Math.abs(v) <= 2 ** 31),
  hex64OrNull: (v) => v === null || (typeof v === 'string' && HEX64.test(v)), ts: (v) => typeof v === 'string' && TS.test(v),
  enum: (...a) => (v) => a.includes(v), flags: (v) => Array.isArray(v) && v.length <= 8 && v.every((x) => typeof x === 'string' && FLAG.test(x)),
  exercise: (v) => typeof v === 'string' && EXERCISE.test(v), const: (c) => (v) => v === c,
};
const COMMON = { schema: T.const('tvijo.learn.event/1'), event_id: T.hex64, seq: T.int, ts: T.ts,
  client: (v) => !!v && typeof v === 'object' && !Array.isArray(v) && Object.keys(v).sort().join() === 'name,version' && T.enum('tvijo-vsix', 'tvijo3code')(v.name) && typeof v.version === 'string' && VERSION.test(v.version) };
const SCHEMA = {
  candidate_presented: { candidate_id: T.hex64, exercise_id: T.exercise, exercise_instance: T.hex64, task_id: T.id, surface: T.enum('apply_coding'),
    context: T.enum('exercise', 'project'), integrity: T.enum('trusted', 'candidate_modified', 'unknown'), observer_ok: T.bool,
    criteria_without_check: T.flags, scope_violation: T.bool, expected_tree_trusted: T.hex64, expected_tree_case: T.hex64, scale_version: T.const('tvijo.learn.scale/1') },
  exposure: { candidate_id: T.hex64, level: T.enum('hint', 'explanation', 'answer'), kind: T.enum('integrity_banner', 'hint', 'explanation', 'answer', 'diff_summary'), requested_by: T.enum('learner', 'system') },
  check: { check_id: T.checkId, candidate_id: T.hex64, kind: T.enum('trusted_test_run', 'counterexample_run', 'review_reproduction', 'agent_test_run'),
    initiator: T.enum('learner', 'agent', 'system'), result: T.enum('pass', 'fail', 'unknown'), bound: T.bool,
    tree_sha256: T.hex64, tree_sha256_after: T.hex64, expected_tree_sha256: T.hex64, input_sha256: T.hex64OrNull, output_sha256: T.hex64, exit_code: T.intOrNull, duration_ms: T.int },
  decision: { request_key: T.hex32, candidate_id: T.hex64, decision: T.enum('accept', 'return', 'request_review'), source: T.enum('human', 'policy_auto', 'dismissed'),
    reason_code: (v) => v === null || ['scope_violation', 'test_failed', 'criteria_gap'].includes(v), observer_ok: T.bool },
  observation_gap: { candidate_id: (v) => v === null || (typeof v === 'string' && HEX64.test(v)), reason: T.enum('append_failed', 'append_timeout', 'seq_gap') },
};
// Returns [] when valid, else error codes. Shape: unknown_type | unknown_field:<f> | missing_field:<f> | invalid_value:<f>.
// Semantics (same function, so the journal and derive agree): inconsistent_bound | kind_initiator_mismatch | reason_not_allowed.
// ctx (optional, from the PINNED exercise manifest): {tasks:Set, exercises:Set, criteria:Set} -> not_in_pack:<f>.
// Values of allowed fields come from the pinned pack or are generated by Learn; an arbitrary secret typed into an allowed
// field is NOT recognised (documented limit, SPEC-304).
function validateEvent(ev, ctx = null) {
  if (!ev || typeof ev !== 'object' || Array.isArray(ev)) return ['schema_invalid'];
  // Own properties only: `k in obj` / `SCHEMA[type]` accept inherited names (constructor, toString, __proto__).
  if (typeof ev.type !== 'string' || !Object.hasOwn(SCHEMA, ev.type)) return ['unknown_type'];
  const spec = { ...COMMON, ...SCHEMA[ev.type] }, errors = [];
  for (const k of Object.keys(ev)) if (k !== 'type' && !Object.hasOwn(spec, k)) errors.push('unknown_field:' + k);
  for (const [k, check] of Object.entries(spec)) {
    if (!Object.hasOwn(ev, k)) { errors.push('missing_field:' + k); continue; }
    // TOTAL by construction: whatever JSON value arrives, a check that throws counts as an invalid value (never an exception).
    let ok = false; try { ok = !!check(ev[k]); } catch { ok = false; }
    if (!ok) errors.push('invalid_value:' + k);
  }
  if (errors.length) return errors;
  if (ev.type === 'check') {
    if (ev.bound === true && !(ev.tree_sha256 === ev.tree_sha256_after && ev.tree_sha256 === ev.expected_tree_sha256)) errors.push('inconsistent_bound');
    if ((ev.result === 'pass' && ev.exit_code !== 0) || (ev.result === 'fail' && (ev.exit_code === null || ev.exit_code === 0))) errors.push('inconsistent_result');   // pass <=> exit 0, fail <=> non-zero exit; unknown carries no claim
    if (SCALE.credited.has(ev.kind) && ev.initiator !== 'learner') errors.push('kind_initiator_mismatch');
    if (ev.kind === 'agent_test_run' && ev.initiator === 'learner') errors.push('kind_initiator_mismatch');
  }
  if (ev.type === 'decision' && ev.reason_code !== null && ev.decision !== 'return') errors.push('reason_not_allowed');
  if (ctx && ev.type === 'candidate_presented') {
    if (ctx.tasks && !ctx.tasks.has(ev.task_id)) errors.push('not_in_pack:task_id');
    if (ctx.exercises && !ctx.exercises.has(ev.exercise_id)) errors.push('not_in_pack:exercise_id');
    if (ctx.criteria && !ev.criteria_without_check.every((c) => ctx.criteria.has(c))) errors.push('not_in_pack:criteria_without_check');
  }
  return errors;
}


module.exports={validateEvent,SCALE,LEVELS,TRUTH,EXPOSURE,MODEL_REV};
